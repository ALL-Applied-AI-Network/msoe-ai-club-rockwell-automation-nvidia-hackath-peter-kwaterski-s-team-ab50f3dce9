#!/usr/bin/env bash
# One-shot setup for a new NVIDIA Brev GPU instance (Isaac Sim already installed).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
SIM="$ROOT/fanuc_er4ia_sim"
SCRIPTS="$ROOT/scripts"

INSTALL_KERNEL=1
SKIP_TUTORIALS=0
DOWNLOAD_MODEL=0
VERIFY_MODEL=0

WORKSPACE="${WORKSPACE:-/workspace}"
COSMOS_VENV="${COSMOS_VENV:-$WORKSPACE/cosmos-venv}"
COSMOS3_FRAMEWORK="${COSMOS3_FRAMEWORK:-$WORKSPACE/cosmos-framework}"
COSMOS3_NANO_PATH="${COSMOS3_NANO_PATH:-$WORKSPACE/models/Cosmos3-Nano}"
ENV_LOCAL="$SCRIPTS/env.local.sh"

usage() {
    cat <<'EOF'
Usage: bash scripts/setup-brev.sh [options]

Assumes Isaac Sim is already on the machine (typical Brev / Isaac Lab images).
Configures host + Cosmos venvs, writes scripts/env.local.sh, runs preflight.

  1. Detect ISAAC (or use --isaac)
  2. Install uv if missing (for tutorial notebooks)
  3. fanuc_er4ia_sim bootstrap (host .venv, textures, 33 tests)
  4. Cosmos venv (PyTorch, transformers==4.57.6, transformers-cosmos3)
  5. Write scripts/env.local.sh (gitignored)
  6. bash scripts/preflight.sh

Options:
  --isaac PATH          Isaac Sim root (must contain python.sh)
  --download-model      hf download nvidia/Cosmos3-Nano (~30GB+; slow)
  --verify-model        After setup, run preflight.sh --load-model
  --skip-tutorials      Skip uv sync / Jupyter kernel
  --no-kernel           With tutorials: skip ipykernel registration
  -h, --help            Show this help

Environment overrides:
  WORKSPACE, COSMOS_VENV, COSMOS3_FRAMEWORK, COSMOS3_NANO_PATH

After setup (every new shell):
  source scripts/env.local.sh
  cd fanuc_er4ia_sim && ./run_sort_pipeline.sh runs/my_run_01
EOF
}

while [ $# -gt 0 ]; do
    case "$1" in
        --isaac)
            ISAAC="$2"
            shift 2
            ;;
        --download-model) DOWNLOAD_MODEL=1; shift ;;
        --verify-model) VERIFY_MODEL=1; shift ;;
        --skip-tutorials) SKIP_TUTORIALS=1; shift ;;
        --no-kernel) INSTALL_KERNEL=0; shift ;;
        -h | --help)
            usage
            exit 0
            ;;
        *)
            echo "Unknown option: $1" >&2
            usage >&2
            exit 1
            ;;
    esac
done

detect_isaac() {
    if [ -n "${ISAAC:-}" ] && [ -x "${ISAAC}/python.sh" ]; then
        echo "$ISAAC"
        return
    fi
    for candidate in \
        /workspace/isaaclab/_isaac_sim \
        /isaacsim \
        "$HOME/isaacsim"; do
        if [ -x "$candidate/python.sh" ]; then
            echo "$candidate"
            return
        fi
    done
    echo ""
}

pass() { echo "[ok] $*"; }
warn() { echo "[warn] $*"; }
fail() { echo "[fail] $*" >&2; exit 1; }

echo "==> Detect Isaac Sim"
ISAAC="$(detect_isaac)"
if [ -z "$ISAAC" ]; then
    fail "Isaac Sim not found. Pass --isaac /path/to/isaacsim (directory with python.sh)."
fi
export ISAAC
pass "ISAAC=$ISAAC"

if ! command -v nvidia-smi >/dev/null 2>&1; then
    warn "nvidia-smi not found — are you on a GPU instance?"
else
    nvidia-smi -L | head -n 1 || true
fi

echo "==> uv (tutorial notebooks)"
if ! command -v uv >/dev/null 2>&1; then
    curl -LsSf https://astral.sh/uv/install.sh | sh
    export PATH="${HOME}/.local/bin:${PATH}"
fi
command -v uv >/dev/null 2>&1 && pass "uv: $(command -v uv)" || warn "uv missing; use --skip-tutorials or install uv manually"

echo "==> Host environment (fanuc_er4ia_sim)"
export HOST_PYTHON_BOOTSTRAP="${ISAAC}/kit/python/bin/python3"
bash "$SIM/bootstrap.sh"

if [ "$SKIP_TUTORIALS" -eq 0 ]; then
    if command -v uv >/dev/null 2>&1; then
        echo "==> Tutorial notebooks"
        SETUP_DEV_SKIP_HOST=1 bash "$SCRIPTS/setup-dev.sh" \
            $([ "$INSTALL_KERNEL" -eq 0 ] && echo --no-kernel)
    else
        warn "skipped tutorials (no uv)"
    fi
else
    pass "skipped tutorials (--skip-tutorials)"
fi

echo "==> Cosmos environment"
export COSMOS_VENV COSMOS3_FRAMEWORK COSMOS3_NANO_PATH
bash "$SCRIPTS/setup-cosmos-venv.sh"

if [ "$DOWNLOAD_MODEL" -eq 1 ]; then
    echo "==> Download Cosmos3-Nano weights (large; one-time per disk)"
    mkdir -p "$(dirname "$COSMOS3_NANO_PATH")"
    "$COSMOS_VENV/bin/pip" install -q "huggingface_hub[cli]" pyyaml
    "$COSMOS_VENV/bin/hf" download nvidia/Cosmos3-Nano --local-dir "$COSMOS3_NANO_PATH"
elif [ ! -f "$COSMOS3_NANO_PATH/config.json" ]; then
    warn "Model not at $COSMOS3_NANO_PATH — re-run with --download-model or copy weights there"
fi

echo "==> Write $ENV_LOCAL"
cat >"$ENV_LOCAL" <<EOF
#!/usr/bin/env bash
# Generated by scripts/setup-brev.sh — do not commit.
export ISAAC=$ISAAC
export COSMOS=$COSMOS_VENV/bin/python
export COSMOS3_NANO_PATH=$COSMOS3_NANO_PATH
export COSMOS3_ROOT=$COSMOS3_FRAMEWORK
export HOST_PYTHON=$SIM/.venv/bin/python
EOF
chmod 600 "$ENV_LOCAL" 2>/dev/null || true
pass "env.local.sh written"

echo "==> Preflight"
# shellcheck source=/dev/null
source "$ENV_LOCAL"
if [ "$VERIFY_MODEL" -eq 1 ]; then
    bash "$SCRIPTS/preflight.sh" --load-model
else
    bash "$SCRIPTS/preflight.sh"
fi

cat <<EOF

Brev setup complete.

Every new SSH session:
  cd $ROOT
  source scripts/env.local.sh

Full pipeline (empty run dir):
  cd fanuc_er4ia_sim
  rm -rf runs/stack_01 && mkdir runs/stack_01
  ./run_sort_pipeline.sh runs/stack_01

Optional model verification:
  bash scripts/preflight.sh --load-model

Stop the Brev instance when idle to save credits.
EOF
